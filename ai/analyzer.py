BASE_DIR = Path(__file__).resolve().parent
DATA_FILE = BASE_DIR / "data" / "events.json"
SCHEMA_FILE = BASE_DIR / "schemas" / "attack_story.json"


def load_events() -> list[dict[str, Any]]:
    """Load normalized security events."""
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


def load_schema() -> dict[str, Any]:
    """Load the Attack Story JSON schema."""
    with open(SCHEMA_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


def get_incident(incident_id: str) -> dict[str, Any] | None:
    """Find an incident generated by the deterministic detector."""

    events = load_events()
    incidents = detect_all(events)

    for incident in incidents:
        if incident["incident_id"] == incident_id:
            return incident

    return None


def validate_attack_story(
    story: dict[str, Any],
    context: dict[str, Any],
) -> None:
    """
    Validate the generated Attack Story against schema and safety constraints.
    Raises ValueError or jsonschema.ValidationError on violation.
    """
    schema = load_schema()

    # 1. JSON Schema validation
    jsonschema.validate(instance=story, schema=schema)

    # 2. Hallucination Protection: Ensure evidence event_ids exist in context
    valid_event_ids = {
        event["event_id"] for event in context["related_events"]
    }

    for ev in story.get("evidence", []):
        event_id = ev.get("event_id")
        if event_id not in valid_event_ids:
            raise ValueError(
                f"Hallucination Detected: Evidence event_id '{event_id}' "
                f"is not present in valid context event IDs: {valid_event_ids}"
            )

    # 3. Non-execution & Human Approval Guarantee
    rec = story.get("recommendation", {})
    if rec.get("requires_human_approval") is not True:
        raise ValueError(
            "Security Safety Violation: 'requires_human_approval' must be True."
        )

    if rec.get("executed") is not False:
        raise ValueError(
            "Security Safety Violation: AI must not execute actions; 'executed' must be False."
        )


def build_investigation_context(
    incident_id: str,
) -> dict[str, Any] | None:
    """
    Build the complete investigation context that would normally
    be supplied to the LLM.
    """

    events = load_events()
    incidents = detect_all(events)

    incident = None

    for item in incidents:
        if item["incident_id"] == incident_id:
            incident = item
            break

    if incident is None:
        return None

    related_events = correlate_incident(incident, events)

    attack_sequence = build_attack_sequence(related_events)

    return {
        "incident": incident,
        "related_events": related_events,
        "attack_sequence": attack_sequence,
    }


