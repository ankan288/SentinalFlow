def explain_event(
    event: dict[str, Any],
    attack_type: str,
) -> str:
    """Explain why an event is relevant without inventing evidence."""

    event_type = event["event_type"]

    explanations = {
        "login_failed": (
            "Failed authentication attempt relevant to the "
            "brute-force sequence."
        ),
        "login_success": (
            "Successful authentication associated with the "
            "detected incident."
        ),
        "privilege_escalation": (
            "Privilege change directly associated with the "
            "privilege-escalation incident."
        ),
        "suspicious_request": (
            "Administrative endpoint access following privilege "
            "escalation."
        ),
        "new_device": (
            "Authentication context indicates use of a newly "
            "observed device."
        ),
        "MFA_change": (
            "MFA configuration changed shortly before sensitive "
            "resource access."
        ),
        "resource_access": (
            "Access to a resource classified as sensitive."
        ),
    }

    return explanations.get(
        event_type,
        f"Event type {event_type} is related to the detected incident."
    )


