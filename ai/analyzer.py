# MAIN ANALYSIS API
# -------------------------------------------------------------------

def analyze_incident(
    incident_id: str,
) -> dict[str, Any]:

    context = build_investigation_context(incident_id)

    if context is None:
        raise ValueError(
            f"Incident {incident_id} was not found."
        )

    if bedrock_available():
        story = bedrock_analysis(
            incident_id,
            context,
        )
    else:
        story = mock_ai_analysis(
            incident_id,
            context,
        )

    # Validate story against JSON schema and safety constraints
    validate_attack_story(story, context)

    return story


